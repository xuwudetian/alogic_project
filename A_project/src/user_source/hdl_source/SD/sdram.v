module sdram_refresh_admission #(
    parameter integer REFRESH_INTERVAL=`SELF_REFRESH_INTERVAL,
    parameter integer MAX_APP_BURST=128,
    parameter integer PIPELINE_MARGIN=64,
    parameter integer POST_REFRESH_GUARD=32
)(
    input clk,input rst,input init_done,input controller_busy,output app_busy
);
    localparam integer COUNT_BITS=$clog2(REFRESH_INTERVAL);
    localparam integer PRE_REFRESH_GUARD=MAX_APP_BURST+PIPELINE_MARGIN;
    reg [COUNT_BITS-1:0] slot_count;
    always @(posedge clk) begin
        if(rst || !init_done) slot_count<=0;
        else if(slot_count==REFRESH_INTERVAL-1) slot_count<=0;
        else slot_count<=slot_count+1'b1;
    end
    assign app_busy=controller_busy || !init_done ||
        slot_count>=REFRESH_INTERVAL-PRE_REFRESH_GUARD ||
        slot_count<POST_REFRESH_GUARD;
endmodule
